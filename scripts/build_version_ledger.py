"""Build the version ledger from the frozen validation files.

Reads results that already exist. Does not rescore anything.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = RESULTS / "registry"


def load(name: str):
    return json.loads((RESULTS / name).read_text())


def row(**fields) -> dict:
    fields.setdefault("medianExcessHold", None)
    fields.setdefault("meanExcessHold", None)
    fields.setdefault("medianExcessPlain", None)
    fields.setdefault("meanExcessPlain", None)
    return fields


def main() -> None:
    validation = load("validation.json")
    summary = load("alts-5000-summary.json")
    champion = load("alts-champion.json")
    trials = [json.loads(line) for line in (RESULTS / "alts-search-log.jsonl").read_text().splitlines() if line.strip()]

    ledger: list[dict] = []
    for version in validation["versions"]:
        for book, algo in version["algos"].items():
            ledger.append(row(
                version=f"{version['id']}/{book}",
                book=book,
                family=version["id"],
                status="rejected" if version["id"] == "v2" and book == "alts" else "recorded",
                scope="calendar-6",
                protocol="six named windows in results/validation.json, not the 5,000-window set",
                n=algo.get("eligible"),
                skipped=algo.get("skipped"),
                bothRate=algo.get("beatBothRate"),
                holdRate=algo.get("beatHoldRate"),
                plainRate=algo.get("beatPlainRate"),
                bullRate=None,
                bearRate=None,
                spec=algo.get("spec"),
                everyDays=algo.get("everyDays"),
                evaluatedAt=validation["generated"],
                decision="superseded" if book == "alts" else "kept-for-that-book",
                source="results/validation.json",
                note=version["note"],
            ))

    ledger.append(row(
        version="alts/cash-200-50-50",
        book="alts",
        family="cowen-cash",
        status="champion",
        scope="windows-5000-full",
        protocol="550 alt lists by the frozen 5,000 windows",
        n=summary["n"],
        skipped=summary["skipped"],
        bothRate=summary["bothRate"],
        holdRate=summary["holdRate"],
        plainRate=summary["plainRate"],
        bullRate=summary["bullRate"],
        bearRate=summary["bearRate"],
        spec=champion["spec"],
        everyDays=14,
        evaluatedAt=summary["updated"],
        decision="kept",
        source="results/alts-5000-summary.json",
        note="Best full pass. Beat-both rate only. Return size was not stored. Restore this if a later rule is worse.",
    ))

    for trial in trials:
        name = trial["name"]
        if name == "cash-200-50-50":
            status, decision = "sample-of-champion", "same rule as the full-pass champion"
        elif name == "oracle-best-of-4":
            status, decision = "not-tradable", "hindsight ceiling, not a rule"
        elif name == "btc0.2-dom0.02-basket0.1":
            status, decision = "grid-best", "best of 45 thresholds on the same sample; not promoted"
        elif trial.get("generation") == "g5-router":
            status, decision = "grid", "one cell of the in-sample router grid; not a separate rule"
        elif name == "equal-when-on":
            status, decision = "rejected", "0.2 points above the cash sample, under the 0.5 point keep bar"
        else:
            status, decision = "rejected", "sample did not beat the kept cash rule by the keep bar"
        ledger.append(row(
            version=f"alts/{name}",
            book="alts",
            family=trial.get("generation"),
            status=status,
            scope="windows-5000-sample",
            protocol="51 lists by every 25th window" if trial.get("n") == 9665 else "same sample, rows with a missing feature dropped",
            n=trial.get("n"),
            skipped=None,
            bothRate=trial.get("bothRate"),
            holdRate=trial.get("holdRate"),
            plainRate=trial.get("plainRate"),
            bullRate=trial.get("bullRate"),
            bearRate=trial.get("bearRate"),
            spec=trial.get("spec"),
            everyDays=14,
            evaluatedAt=trial.get("at"),
            decision=decision,
            source="results/alts-search-log.jsonl",
            note=trial.get("note"),
        ))

    OUT.mkdir(exist_ok=True)
    ledger_path = OUT / "ledger.jsonl"

    def pct(value) -> str:
        return "n/a" if value is None else f"{100 * value:.1f}%"

    lines = [
        "# Scored rebalance versions",
        "",
        "Generated by `scripts/build_version_ledger.py`. Do not edit the numbers by hand.",
        "The line-level record is `ledger.jsonl`. Raw trial output remains `results/alts-search-log.jsonl`.",
        "",
        "The calendar and 5,000-window sections below store how often a book finished ahead, not by how much. The named-stretch sections store the dollar gap.",
        "",
        "## Champion",
        "",
        "Alt coins. Cash when bitcoin is under its 200-day average, or dominance is above its 50-day average, or total cap is under its 50-day average.",
        f"Full pass {summary['updated']}: {summary['n']} scored tests, {summary['skipped']} skipped, {summary['books']} lists, {summary['windows']} windows.",
        f"Beat both {pct(summary['bothRate'])}. Beat hold {pct(summary['holdRate'])}. Beat plain {pct(summary['plainRate'])}. Bitcoin-up {pct(summary['bullRate'])}. Bitcoin-down {pct(summary['bearRate'])}.",
        "",
        "## Earlier four-book check",
        "",
        "Different test. Six calendar windows, not the 5,000-window set. Do not compare these rates with the champion.",
        "",
        "| Version | Book | Tests | Beat both | Beat hold | Beat plain |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for item in ledger:
        if item["scope"] != "calendar-6":
            continue
        lines.append(
            f"| {item['version']} | {item['book']} | {item['n']} | {pct(item['bothRate'])} | {pct(item['holdRate'])} | {pct(item['plainRate'])} |"
        )
    lines += [
        "",
        "## Sample trials on the frozen 5,000-window draw",
        "",
        "A sample cannot replace the champion. The router grid is 45 looks at one sample; only its best row is listed here.",
        "",
        "| Version | Family | Tests | Beat both | Up | Down | Decision |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for item in ledger:
        if item["scope"] != "windows-5000-sample" or item["status"] == "grid":
            continue
        lines.append(
            f"| {item['version']} | {item['family']} | {item['n']} | {pct(item['bothRate'])} | {pct(item['bullRate'])} | {pct(item['bearRate'])} | {item['decision']} |"
        )
    remaining = load("remaining-scores.json")
    for item in remaining["pair"]:
        full = item.get("full") or {}
        beats = item.get("beatsHold")
        scored = item.get("scored")
        chosen = item["id"] == "stay300-floor10"
        ledger.append(row(
            version=f"btc-eth/{item['id']}",
            book="btc-eth",
            family="pair-named-8",
            status="default" if chosen else "recorded",
            scope="named-8",
            protocol="Eight named stretches from 2017-08-17 to 2026-11-20. 10000 USDT, 10 bps, 5 bps, every 14 days.",
            n=scored,
            skipped=None,
            bothRate=None,
            holdRate=(beats / scored) if scored else None,
            plainRate=None,
            bullRate=None,
            bearRate=None,
            medianExcessHold=(full.get("equity") - full.get("hold")) if full.get("equity") is not None and full.get("hold") is not None else None,
            meanExcessHold=None,
            medianExcessPlain=(full.get("equity") - full.get("plain")) if full.get("equity") is not None and full.get("plain") is not None else None,
            meanExcessPlain=None,
            finalEquity=full.get("equity"),
            holdEquity=full.get("hold"),
            plainEquity=full.get("plain"),
            endingBtc=full.get("btc"),
            endingEth=full.get("eth"),
            keepsBoth=item.get("keepsBothOnFull"),
            byWindow=item.get("byWindow"),
            spec=item.get("spec"),
            everyDays=14,
            evaluatedAt=remaining["at"],
            decision="default: keeps both coins and the large gain" if chosen else "available, not the default",
            source="results/remaining-scores.json",
            note="Hold-rate here is named stretches that finished ahead of holding, not the 5,000-window beat-both rate.",
        ))
    defaults = {
        ("btc-alts", "stay200"),
        ("alts-stable", "stay200"),
        ("alts", "cash-200-50-50"),
    }
    for item in remaining["books"]:
        chosen = (item["book"], item["id"]) in defaults
        ledger.append(row(
            version=f"{item['book']}/{item['id']}",
            book=item["book"],
            family="book-named-4",
            status="default" if chosen else "recorded",
            scope="named-4",
            protocol="2022 bear, 2023-24, 2024-26, and 2021-11-20 through 2026-11-20. Same costs. A missing listing is skipped, not dropped.",
            n=item.get("n"),
            skipped=item.get("skipped"),
            bothRate=item.get("bothRate"),
            holdRate=None,
            plainRate=None,
            bullRate=item.get("bullRate"),
            bearRate=item.get("bearRate"),
            medianExcessHold=item.get("medianExcessHoldFull"),
            spec=None,
            everyDays=14,
            evaluatedAt=remaining["at"],
            decision="default for this book" if chosen else "logged, not the default",
            source="results/remaining-scores.json",
            note="Bull rate is the 2023-24 and 2024-26 stretches. Bear rate is the 2022 bear only. Median gap is the long stretch versus holding.",
        ))
    long_rows = load("btc-eth-long.json")
    for item in long_rows["rows"]:
        ledger.append(row(
            version=item["version"],
            book=item["book"],
            family="pair-overlap-3.5y",
            status="recorded",
            scope="overlap-3.5y",
            protocol="Overlapping 3.5-year windows plus the named stretches inside scripts/tune_btc_eth.ts. Not the eight-stretch decision set.",
            n=item.get("n"),
            skipped=None,
            bothRate=item.get("bothRate"),
            holdRate=None,
            plainRate=None,
            bullRate=item.get("bullRate"),
            bearRate=item.get("bearRate"),
            medianExcessHold=item.get("medianExcessHold"),
            medianExcessPlain=item.get("medianExcessPlain"),
            medianBtcStack=item.get("medianBtcStack"),
            medianEthStack=item.get("medianEthStack"),
            spec=item.get("spec"),
            everyDays=14,
            evaluatedAt=item.get("at"),
            decision="sample only; the default comes from the named eight stretches",
            source="results/btc-eth-long.json",
            note=f"windows field {item.get('windows')}. A 100% beat-both here can still end with no ether.",
        ))

    lines += [
        "",
        "## Named stretches, bitcoin and ether, 2017-2026",
        "",
        "Different test from the tables above. Equity is the full span. Hold-wins counts the eight named stretches, including that full span. The default is the 300-day switch with a 10% floor: it keeps both coins and still makes the large gain. The no-floor 300-day rule makes more dollars and ends with no ether, so it is not the default.",
        "",
        "| Version | Full equity | Hold | Plain | BTC left | ETH left | Stretches ahead of hold | Default |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for item in ledger:
        if item["scope"] != "named-8":
            continue
        lines.append(
            f"| {item['version']} | {item.get('finalEquity')} | {item.get('holdEquity')} | {item.get('plainEquity')} | {None if item.get('endingBtc') is None else round(item['endingBtc'], 2)} | {None if item.get('endingEth') is None else round(item['endingEth'], 2)} | {None if item.get('holdRate') is None else round(item['holdRate'] * item['n'])} / {item['n']} | {'yes' if item['status'] == 'default' else ''} |"
        )
    lines += [
        "",
        "## Four stretches, the other three books",
        "",
        "| Version | Tests | Skipped | Beat both | Bull stretches | 2022 bear | Median gap vs hold | Default |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for item in ledger:
        if item["scope"] != "named-4":
            continue
        gap = item.get("medianExcessHold")
        gap_text = "n/a" if gap is None else str(round(gap))
        lines.append(
            f"| {item['version']} | {item['n']} | {item['skipped']} | {pct(item['bothRate'])} | {pct(item['bullRate'])} | {pct(item['bearRate'])} | {gap_text} | {'yes' if item['status'] == 'default' else ''} |"
        )
    lines += [
        "",
        "## Not a scored period",
        "",
        "Prices end on 2026-11-20. December 2026 through November 2029 is not in the test. The retired 75% alt target was not restored. The full alt pass stays 62.9% beat-both.",
        "",
    ]
    ledger_path.write_text("".join(json.dumps(item, separators=(",", ":")) + "\n" for item in ledger))
    (OUT / "VERSIONS.md").write_text("\n".join(lines))
    print(f"{len(ledger)} rows -> {ledger_path}")


if __name__ == "__main__":
    main()
